"""HTML and Markdown metadata stripping.

These are text formats, so the Layer A cleaner also applies to their bodies.
This module handles only the structured provenance: HTML ``<meta>`` generator
tags, JSON-LD ``AIGeneratedContent`` blocks, ``data-ai-*`` attributes, and
Markdown YAML frontmatter keys.
"""

from __future__ import annotations

import json
import re

from .common import MetaResult

# ---------------------------------------------------------------- HTML

META_GENERATOR_RE = re.compile(
    rb"<meta\b[^>]*\bname\s*=\s*[\"']?(generator|author|application-name"
    rb"|ai-generated|openai|dc\.creator)[\"']?[^>]*>",
    re.I,
)
META_PROP_RE = re.compile(
    rb"<meta\b[^>]*\bproperty\s*=\s*[\"'](?:og:)?(?:article:author)[\"'][^>]*>", re.I
)
JSONLD_RE = re.compile(
    rb"<script\b[^>]*type\s*=\s*[\"']application/ld\+json[\"'][^>]*>(.*?)</script>",
    re.I | re.S,
)
AI_ATTR_RE = re.compile(
    rb"\s(data-ai-[\w-]+|data-c2pa[\w-]*)\s*=\s*(\"[^\"]*\"|'[^']*'|[^\s>]+)", re.I
)
HTML_COMMENT_RE = re.compile(
    rb"<!--(?:(?!-->).)*?(generated by|c2pa|content credentials|chatgpt|claude"
    rb"|copilot|midjourney).*?-->",
    re.I | re.S,
)

JSONLD_AI_KEYS = ("AIGeneratedContent", "aiGenerated", "generatorName", "creator")


def _jsonld_is_ai(body: bytes) -> str | None:
    try:
        obj = json.loads(body.decode("utf-8", "replace"))
    except (ValueError, UnicodeDecodeError):
        text = body.decode("utf-8", "replace")
        for key in JSONLD_AI_KEYS:
            if key in text:
                return key
        return None

    found: list[str] = []

    def walk(node: object) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                if k in JSONLD_AI_KEYS or (
                    k == "@type" and isinstance(v, str) and v in JSONLD_AI_KEYS
                ):
                    found.append(k if k != "@type" else str(v))
                walk(v)
        elif isinstance(node, list):
            for item in node:
                walk(item)

    walk(obj)
    return ", ".join(sorted(set(found))) if found else None


def inspect_html(data: bytes) -> MetaResult:
    res = MetaResult(format="html")
    for m in META_GENERATOR_RE.finditer(data):
        res.add("generator", m.group(0)[:200].decode("utf-8", "replace"), len(m.group(0)))
    for m in META_PROP_RE.finditer(data):
        res.add("docprops", m.group(0)[:200].decode("utf-8", "replace"), len(m.group(0)))
    for m in JSONLD_RE.finditer(data):
        hit = _jsonld_is_ai(m.group(1))
        if hit:
            res.add("jsonld", f"JSON-LD block with {hit}", len(m.group(0)))
    for m in AI_ATTR_RE.finditer(data):
        res.add("attribute", m.group(0).strip()[:120].decode("utf-8", "replace"))
    for m in HTML_COMMENT_RE.finditer(data):
        res.add("comment", m.group(0)[:160].decode("utf-8", "replace"), len(m.group(0)))
    return res


def clean_html(data: bytes) -> tuple[bytes, MetaResult]:
    res = inspect_html(data)
    out = data
    counts: dict[str, int] = {}

    out, counts["meta generator/author tags"] = META_GENERATOR_RE.subn(b"", out)
    out, counts["meta property tags"] = META_PROP_RE.subn(b"", out)
    out, counts["data-ai attributes"] = AI_ATTR_RE.subn(b"", out)
    out, counts["AI comments"] = HTML_COMMENT_RE.subn(b"", out)

    def drop_ai_jsonld(m: re.Match[bytes]) -> bytes:
        return b"" if _jsonld_is_ai(m.group(1)) else m.group(0)

    before = out
    out = JSONLD_RE.sub(drop_ai_jsonld, out)
    counts["JSON-LD blocks"] = 1 if out != before else 0

    for label, n in counts.items():
        if n:
            res.actions.append(f"removed {n} {label}")
    return out, res


# ------------------------------------------------------------ Markdown

# Optional UTF-8 BOM, then a --- fenced YAML block at the very start.
FRONTMATTER_RE = re.compile(rb"\A(?:\xef\xbb\xbf)?---\r?\n(.*?)\r?\n---[ \t]*\r?\n", re.S)

AI_FRONTMATTER_KEYS = re.compile(
    r"^(ai_generated|ai-generated|aigenerated|generated_by|generator|model"
    r"|assistant|tool|llm|openai|anthropic|claude|gpt|copilot|prompt"
    r"|ai_model|ai_tool|generated_with|created_with|c2pa)\b",
    re.I,
)


def _split_frontmatter(data: bytes) -> tuple[bytes, bytes, bytes] | None:
    m = FRONTMATTER_RE.match(data)
    if not m:
        return None
    return m.group(0), m.group(1), data[m.end() :]


def inspect_markdown(data: bytes) -> MetaResult:
    res = MetaResult(format="markdown")
    parts = _split_frontmatter(data)
    if parts is None:
        return res
    _, body, _rest = parts
    for line in body.decode("utf-8", "replace").splitlines():
        key = line.split(":", 1)[0].strip()
        if key and AI_FRONTMATTER_KEYS.match(key):
            res.add("frontmatter", f"frontmatter key {line.strip()[:120]!r}")
    return res


def clean_markdown(data: bytes) -> tuple[bytes, MetaResult]:
    res = inspect_markdown(data)
    parts = _split_frontmatter(data)
    if parts is None:
        return data, res
    _whole, body, rest = parts

    kept: list[str] = []
    removed = 0
    skipping = False
    for line in body.decode("utf-8", "replace").splitlines():
        stripped = line.strip()
        is_continuation = line[:1] in (" ", "\t", "-") and skipping
        if is_continuation:
            removed += 1
            continue
        key = stripped.split(":", 1)[0].strip()
        if key and AI_FRONTMATTER_KEYS.match(key):
            skipping = True
            removed += 1
            continue
        skipping = False
        kept.append(line)

    if not removed:
        return data, res

    remaining = "\n".join(kept).strip()
    if remaining:
        new_front = b"---\n" + remaining.encode("utf-8") + b"\n---\n"
    else:
        new_front = b""
        res.actions.append("frontmatter block was empty after stripping; removed it")
    res.actions.append(f"removed {removed} AI-related frontmatter line(s)")
    return new_front + rest, res
